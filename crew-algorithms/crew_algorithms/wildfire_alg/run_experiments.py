"""
Run WILDFIRE experiments offline using presets from experiment_presets.json.

Reads experiment presets (generated by generate_experiment_presets.py),
translates hierarchies into Hydra team_config overrides, and spawns
game subprocesses with seed control and parallelism management.

Usage:
    cd crew-algorithms
    python crew_algorithms/wildfire_alg/run_experiments.py                        # All presets, default seeds
    python crew_algorithms/wildfire_alg/run_experiments.py --presets "Cut_Trees*"  # Filter by pattern
    python crew_algorithms/wildfire_alg/run_experiments.py --seeds 42 137 256      # Override seeds
    python crew_algorithms/wildfire_alg/run_experiments.py --parallel 4            # Max concurrency
    python crew_algorithms/wildfire_alg/run_experiments.py --dry-run               # Print commands only
"""

import argparse
import fnmatch
import json
import os
import signal
import subprocess
import sys
import time
from datetime import datetime

LOG_DIR = "experiment_logs"


def preset_to_team_config(preset: dict) -> dict:
    """Convert preset hierarchy format to __main__.py team_config format.

    Preset: {"managers": ["AGENT_4"], "config": {"AGENT_4": {"children": ["AGENT_1"...], ...}}}
    team_config: {"humans": [], "managers": {4: {"children": [1...], "type": "...", "team_name": "..."}}}
    """
    hierarchy = preset["hierarchy"]
    managers = {}
    for agent_name, config in hierarchy["config"].items():
        agent_id = int(agent_name.split("_")[1])
        children_ids = [int(c.split("_")[1]) for c in config["children"]]
        managers[agent_id] = {
            "children": children_ids,
            "type": config["type"],
            "team_name": config["team_name"],
        }
    return {"humans": [], "managers": managers}


def dict_to_omegaconf(d):
    """Convert a Python dict to an OmegaConf override string."""
    if isinstance(d, dict):
        items = [f"{k}: {dict_to_omegaconf(v)}" for k, v in d.items()]
        return "{" + ", ".join(items) + "}"
    elif isinstance(d, list):
        return "[" + ", ".join(dict_to_omegaconf(x) for x in d) + "]"
    elif isinstance(d, str):
        return f'"{d}"'
    else:
        return str(d)


def team_config_override(preset: dict) -> str:
    """Build the Hydra team_config override for a WILDFIRE preset."""
    team_config = preset_to_team_config(preset)
    return f"++envs.team_config={dict_to_omegaconf(team_config)}"


def build_command(preset: dict, seed: int, noop: bool = False, algorithm: str = "WILDFIRE", llm_model: str = None, no_graphics: str = "false") -> list:
    """Build the full command to run an algorithm (WILDFIRE or a baseline)."""
    # default llm_model will be appended by caller if provided
    if noop:
        cmd = [
            sys.executable, "-m", "crew_algorithms.wildfire_alg.algorithms.WILDFIRE.test_noop",
            f"envs.level={preset['level']}",
            f"envs.seed={seed}",
        ]
    elif algorithm == "WILDFIRE":
        team_config_str = team_config_override(preset)
        cmd = [
            sys.executable, "-m", "crew_algorithms.wildfire_alg.algorithms.WILDFIRE",
            f"envs.level={preset['level']}",
            f"envs.seed={seed}",
            "envs.collaboration_mode=ai_control",
            team_config_str,
        ]
    else:
        # Baseline algorithms (CAMON, COELA, Embodied, HMAS_2)
        # No team_config needed — baselines manage their own agent structure
        cmd = [
            sys.executable, "-m", f"crew_algorithms.wildfire_alg.algorithms.{algorithm}",
            f"envs.level={preset['level']}",
            f"envs.seed={seed}",
            "envs.collaboration_mode=ai_control",
        ]
    # Append llm_model override for Hydra if provided
    if llm_model:
        cmd.append(f"envs.llm_model={llm_model}")
    if no_graphics:
        cmd.append(f"envs.no_graphics={no_graphics}")
    return cmd

def main():
    parser = argparse.ArgumentParser(description="Run WILDFIRE experiments from presets")
    parser.add_argument(
        "--presets-file",
        default=None,
        help="Path to experiment_presets.json (default: auto-detect)",
    )
    parser.add_argument(
        "--presets",
        nargs="*",
        default=None,
        help="Filter presets by name pattern (glob). E.g. 'Cut_Trees*' 'Scout_Fire*'",
    )
    parser.add_argument(
        "--seeds",
        nargs="*",
        type=int,
        default=None,
        help="Override seeds for ALL presets (replaces per-level seeds). E.g. 42 137 256",
    )
    parser.add_argument(
        "--parallel",
        type=int,
        default=1,
        help="Max concurrent experiments (default: 1)",
    )
    parser.add_argument(
        "--stagger",
        type=int,
        default=20,
        help="Seconds between launching parallel experiments (default: 20)",
    )
    parser.add_argument(
        "--runs",
        type=int,
        default=1,
        help="Number of times to run each preset+seed combination (default: 1)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print commands without running them",
    )
    parser.add_argument(
        "--noop",
        action="store_true",
        help="Run noop baseline (test_noop.py) instead of the full algorithm",
    )
    parser.add_argument(
        "--algorithm",
        choices=["WILDFIRE", "CAMON", "COELA", "Embodied", "HMAS_2"],
        default="WILDFIRE",
        help="Algorithm to run (default: WILDFIRE)",
    )
    parser.add_argument(
        "--llm_model",
        choices=["gpt", "qwen", "deepseek"],
        default="gpt",
        help="Top-level LLM model family to use (default: gpt). Passed to Hydra as llm_model=<value>",
    )
    parser.add_argument(
        "--no_graphics",
        choices=["true", "false"],
        default="false",
        help="Whether to disable graphics in the environment (default: false). Passed to Hydra as envs.no_graphics=<value>",
    )
    args = parser.parse_args()

    # Find presets file
    if args.presets_file:
        presets_path = args.presets_file
    else:
        # Same directory as this script
        script_dir = os.path.dirname(os.path.abspath(__file__))
        presets_path = os.path.join(script_dir, "experiment_presets.json")

    if not os.path.exists(presets_path):
        print(f"ERROR: Presets file not found: {presets_path}")
        print("Run generate_experiment_presets.py first to create it.")
        sys.exit(1)

    with open(presets_path) as f:
        all_presets = json.load(f)

    # print(f"Loaded {len(all_presets)} presets from {presets_path}")

    # Filter presets by pattern
    if args.presets:
        filtered = {}
        for pattern in args.presets:
            for key in all_presets:
                if fnmatch.fnmatch(key, pattern):
                    filtered[key] = all_presets[key]
        all_presets = filtered
        # print(f"Filtered to {len(all_presets)} presets: {list(all_presets.keys())}")

    if not all_presets:
        # print("No presets matched. Available presets:")
        with open(presets_path) as f:
            available = json.load(f)
        for key in sorted(available.keys()):
            print(f"  {key}")
        sys.exit(1)

    # Build experiment list: (name, command)
    # Each preset has a "seeds" list. --seeds overrides all of them.
    # --runs repeats each preset+seed combination N times.
    experiments = []
    for preset_key, preset in all_presets.items():
        seeds = args.seeds if args.seeds else preset.get("seeds", [42])
        for seed in seeds:
            for run in range(1, args.runs + 1):
                run_suffix = f"_run{run}" if args.runs > 1 else ""
                name = f"{args.algorithm}_{preset_key}_seed{seed}{run_suffix}"
                cmd = build_command(preset, seed, noop=args.noop, algorithm=args.algorithm, llm_model=args.llm_model, no_graphics=args.no_graphics)
                experiments.append((name, cmd))

    for name, cmd in experiments:
        print(f"Experiment: {name}")
        if args.algorithm == "WILDFIRE" and not args.noop:
            preset_key = name.split("_seed", 1)[0].removeprefix("WILDFIRE_")
            print(f"  team_config: {team_config_override(all_presets[preset_key])}")
        
        print(f"\n")


if __name__ == "__main__":
    main()
